-- File metadata. The bytes stay in storage (Supabase bucket ticket-attachments,
-- or the server's local folder). Each file belongs to exactly one ticket or
-- one form submission.
CREATE TABLE IF NOT EXISTS attachments (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- The storage object key, also used in the download URL.
  storage_key         VARCHAR(200) NOT NULL UNIQUE,
  ticket_id           BIGINT       REFERENCES tickets (id) ON DELETE CASCADE,
  form_submission_id  BIGINT       REFERENCES form_submissions (id) ON DELETE CASCADE,
  file_name           VARCHAR(260) NOT NULL,
  size_bytes          BIGINT       NOT NULL DEFAULT 0,
  content_type        VARCHAR(150),
  storage_backend     VARCHAR(10)  NOT NULL DEFAULT 'supabase',
  uploaded_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_attachments_backend CHECK (storage_backend IN ('supabase', 'local')),
  CONSTRAINT ck_attachments_one_parent CHECK (
       (ticket_id IS NOT NULL AND form_submission_id IS NULL)
    OR (ticket_id IS NULL     AND form_submission_id IS NOT NULL)
  )
);

-- Workspace settings shared by the whole IT team: a single row (id = 1).
-- Per-browser preferences (theme) and retired options are not stored here;
-- ticket numbering lives in ticket_sequences.
CREATE TABLE IF NOT EXISTS settings (
  id                                  INTEGER     PRIMARY KEY,
  default_view                        VARCHAR(16) NOT NULL DEFAULT 'kanban',
  show_kanban                         BOOLEAN     NOT NULL DEFAULT TRUE,
  show_list                           BOOLEAN     NOT NULL DEFAULT TRUE,
  show_history                        BOOLEAN     NOT NULL DEFAULT TRUE,
  show_handbook                       BOOLEAN     NOT NULL DEFAULT TRUE,
  show_analytics                      BOOLEAN     NOT NULL DEFAULT TRUE,
  show_forms                          BOOLEAN     NOT NULL DEFAULT TRUE,
  show_form_history                   BOOLEAN     NOT NULL DEFAULT TRUE,
  completed_ticket_retention_minutes  INTEGER     NOT NULL DEFAULT 60,
  chat_knowledge_mode                 VARCHAR(8)  NOT NULL DEFAULT 'scoped',
  default_category_id                 BIGINT      REFERENCES categories (id),
  -- Default assignee name for tickets an admin creates.
  operator_name                       VARCHAR(200),
  updated_at                          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_settings_single_row CHECK (id = 1),
  CONSTRAINT ck_settings_default_view CHECK (default_view IN ('kanban', 'list', 'history', 'handbook', 'analytics', 'forms', 'formHistory')),
  CONSTRAINT ck_settings_chat_mode CHECK (chat_knowledge_mode IN ('scoped', 'full')),
  CONSTRAINT ck_settings_retention CHECK (completed_ticket_retention_minutes > 0)
);


